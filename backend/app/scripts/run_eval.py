"""Run the 15 evaluation scenarios through the rule-based assistant and the AI.

For every scenario it records the facts sent, the rule-based answer, and three AI
answers (to see how consistent the model is), with the schema and grounding
checks applied to each. Then it builds a blind rating sheet: the two answers per
scenario are shuffled and labelled A and B, so raters don't know which is which.

Run from backend/ after seed_eval:
    python -m app.scripts.run_eval             # needs OPENAI_API_KEY in .env for the AI side
    python -m app.scripts.run_eval --runs 3

Writes:
    docs/eval/results.md        everything side by side, for the report
    docs/eval/rating-sheet.csv  what the two raters fill in (blind)
    data/eval/rating-key.csv    which of A/B was the AI (kept out of the raters' sight)
    data/eval/results.json      raw data for the scorer
"""
import argparse
import csv
import json
import random
from datetime import date
from pathlib import Path

from sqlalchemy import select

from app.core.config import get_settings
from app.db.session import SessionLocal
from app.models import Client, Lead, User
from app.scripts.seed_eval import EVAL_EMAIL, SCENARIOS
from app.services import grounding
from app.services.ai_assistant import PROMPT_VERSION, ask_model, build_context, rule_based

ROOT = Path(__file__).resolve().parents[3]


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--runs", type=int, default=3, help="AI answers per scenario")
    ap.add_argument("--seed", type=int, default=2026, help="for the A/B shuffle")
    args = ap.parse_args()
    s = get_settings()
    ai_on = bool(s.openai_api_key)
    rng = random.Random(args.seed)
    results = []

    with SessionLocal() as db:
        agent = db.scalar(select(User).where(User.email == EVAL_EMAIL))
        if agent is None:
            raise SystemExit("Create the scenarios first: python -m app.scripts.seed_eval")
        for n, title, good in SCENARIOS:
            c = db.scalar(select(Client).where(Client.email == f"eval-{n:02d}@example.com"))
            lead = db.scalar(select(Lead).where(Lead.client_id == c.id))
            ctx = build_context(db, lead)
            rules = rule_based(ctx).model_dump()
            r_ok, r_issues = grounding.check(rules, ctx)
            ai_runs = []
            if ai_on:
                for _ in range(args.runs):
                    out, problems, secs = ask_model(ctx)
                    ai_runs.append({"answer": out.model_dump() if out else None, "problems": problems,
                                    "seconds": round(secs, 2)})
            results.append({"n": n, "title": title, "good": good, "facts": ctx,
                            "rules": rules, "rules_grounded": r_ok, "rules_issues": r_issues, "ai": ai_runs})
            print(f"{n:2d}. {title}: rules -> {rules['action_type']}"
                  + (f"; AI -> {[r['answer']['action_type'] if r['answer'] else 'rejected' for r in ai_runs]}" if ai_on else ""))

    (ROOT / "data" / "eval").mkdir(parents=True, exist_ok=True)
    (ROOT / "docs" / "eval").mkdir(parents=True, exist_ok=True)
    (ROOT / "data" / "eval" / "results.json").write_text(json.dumps(
        {"prompt_version": PROMPT_VERSION, "model": s.openai_model if ai_on else None, "date": str(date.today()),
         "results": results}, indent=2, default=str), encoding="utf-8")

    # Blind rating sheet: first AI run vs rules, order shuffled per scenario.
    with open(ROOT / "docs" / "eval" / "rating-sheet.csv", "w", newline="", encoding="utf-8") as f, \
            open(ROOT / "data" / "eval" / "rating-key.csv", "w", newline="", encoding="utf-8") as k:
        sheet, key = csv.writer(f), csv.writer(k)
        sheet.writerow(["scenario", "answer", "recommended_action", "draft_message",
                        "grounded_1to4", "right_action_1to4", "specific_1to4", "draft_quality_1to4", "rater", "comment"])
        key.writerow(["scenario", "A", "B"])
        for r in results:
            ai = next((x["answer"] for x in r["ai"] if x["answer"]), None)
            pair = [("rules", r["rules"]), ("ai", ai)] if ai else [("rules", r["rules"])]
            rng.shuffle(pair)
            labels = dict(zip("AB", (p[0] for p in pair)))
            key.writerow([r["n"], labels.get("A", ""), labels.get("B", "")])
            for label, (_, ans) in zip("AB", pair):
                sheet.writerow([r["n"], label, ans["recommended_action"], ans["draft_message"], "", "", "", "", "", ""])

    write_markdown(results, ai_on, s.openai_model)
    print(f"\nWrote docs/eval/results.md and docs/eval/rating-sheet.csv"
          + ("" if ai_on else " (rule-based only: add OPENAI_API_KEY to backend/.env to include the AI)"))


def write_markdown(results: list[dict], ai_on: bool, model: str) -> None:
    lines = ["# AI evaluation: raw results", "",
             f"Generated by `python -m app.scripts.run_eval` on {date.today()} with prompt {PROMPT_VERSION}"
             + (f" and model `{model}`." if ai_on else ". **The AI side wasn't run: no API key was set.**"), "",
             "| # | Scenario | Rule-based action | AI action (3 runs) | AI answers that passed both checks |",
             "| --- | --- | --- | --- | --- |"]
    for r in results:
        if r["ai"]:
            kinds = [x["answer"]["action_type"] if x["answer"] else "rejected" for x in r["ai"]]
            passed = sum(x["answer"] is not None for x in r["ai"])
            ai_cell, pass_cell = ", ".join(kinds), f"{passed} of {len(r['ai'])}"
        else:
            ai_cell, pass_cell = "not run", "–"
        lines.append(f"| {r['n']} | {r['title']} | {r['rules']['action_type']} | {ai_cell} | {pass_cell} |")
    for r in results:
        lines += ["", f"## {r['n']}. {r['title']}", "", f"*A good answer:* {r['good']}.", "",
                  "**Rule-based**", "", f"> **Action:** {r['rules']['recommended_action']}  ",
                  f"> **Why:** {r['rules']['reasoning']}  ", f"> **Draft:** {r['rules']['draft_message'].replace(chr(10), ' ')}"]
        for i, x in enumerate(r["ai"], 1):
            lines += ["", f"**AI, run {i}** ({x['seconds']} s)", ""]
            if x["answer"]:
                a = x["answer"]
                lines += [f"> **Intent:** {a['intent_level']}  ", f"> **Action:** {a['recommended_action']}  ",
                          f"> **Why:** {a['reasoning']}  ", f"> **Draft:** {a['draft_message'].replace(chr(10), ' ')}"]
            else:
                lines.append(f"> Rejected: {'; '.join(x['problems'])}")
    (ROOT / "docs" / "eval" / "results.md").write_text("\n".join(lines) + "\n", encoding="utf-8")


if __name__ == "__main__":
    main()
